"""One allocation/INIT/CHECK service, independent of CPU/BFM execution.

Actual memory operations are provider-specific and explicitly labelled.
Neither allocating a virtual address nor selecting a policy preloads memory.
A backdoor provider is usable only after frontdoor equivalence validation.
No silent fast -> strict fallback and no invented hardware cycles.
"""
from __future__ import annotations
from dataclasses import dataclass, field
import time
from typing import Protocol

from tools.memory_plan import VirtualAllocation, VirtualRegion


class MemoryAccessError(RuntimeError):
    pass


class MemoryMismatch(AssertionError):
    pass


@dataclass(frozen=True)
class Pattern:
    kind: str = "counter8"
    seed: int = 0

    def __post_init__(self):
        if self.kind not in ("counter8", "constant", "address_xor"):
            raise ValueError(f"unsupported memory pattern {self.kind!r}")
        if not isinstance(self.seed, int) or not 0 <= self.seed <= 0xffffffff:
            raise ValueError("seed must be an unsigned 32-bit integer")

    def chunk(self, phys: int, length: int) -> bytes:
        """Always identical regardless of chunk size or traversal order."""
        if not 0 <= phys <= (1 << 64) - 1 or length < 0 or phys + length > 1 << 64:
            raise ValueError("invalid physical pattern range")
        if self.kind == "constant":
            return bytes([self.seed & 255]) * length
        if self.kind == "counter8":
            return bytes(((phys + j + self.seed) & 255) for j in range(length))
        return bytes((((phys + j) ^ self.seed) & 255) for j in range(length))


class MemoryProvider(Protocol):
    """Providers must not claim backdoor verification before cross-checks."""
    validated_backdoor: bool
    frontdoor_available: bool

    async def frontdoor_read(self, phys: int, length: int) -> bytes: ...
    async def frontdoor_write(self, phys: int, data: bytes) -> None: ...
    async def backdoor_read(self, phys: int, length: int) -> bytes: ...
    async def backdoor_write(self, phys: int, data: bytes) -> None: ...


class HostSparseMemory:
    """Cocotbext SparseMemoryRegion-backed model, no new SRAM implementation.

    No RTL bus traffic is generated by direct accesses. The backing object
    must expose async read(offset,length) and write(offset,data).
    This provider is marked validated only by the caller AFTER a separate
    AXI frontdoor consistency test proves that these offsets map correctly.
    """
    def __init__(self, sparse_region, physical_base: int):
        self.memory = sparse_region
        self.base = physical_base
        # A newly registered backing is NEVER prevalidated just because
        # it is host memory. Only CombinedMemoryProvider can establish the
        # frontdoor/backdoor equivalence against actual routed AXI traffic.
        self.validated_backdoor = False
        self.frontdoor_available = False

    async def backdoor_read(self, phys, length):
        return bytes(await self.memory.read(phys - self.base, length))

    async def backdoor_write(self, phys, data):
        await self.memory.write(phys - self.base, data)

    async def frontdoor_read(self, phys, length):
        raise MemoryAccessError("host sparse memory needs an attached AXI frontdoor")

    async def frontdoor_write(self, phys, data):
        raise MemoryAccessError("host sparse memory needs an attached AXI frontdoor")


class CombinedMemoryProvider:
    """Compose an existing active BFM and a host/RTL backdoor for same bytes.

    Never silently validate a backdoor. First use a quiescent sacrificial
    scratch range, with genuine frontdoor transfers and independent backdoor
    comparison in BOTH directions. Not for live CPU ports with active BFMs.
    """
    def __init__(self, frontdoor, backdoor):
        self.frontdoor = frontdoor
        self.backdoor = backdoor
        self.validated_backdoor = False
        self.frontdoor_available = bool(frontdoor.frontdoor_available)

    async def frontdoor_read(self, phys, length):
        return await self.frontdoor.frontdoor_read(phys, length)

    async def frontdoor_write(self, phys, data):
        await self.frontdoor.frontdoor_write(phys, data)

    async def backdoor_read(self, phys, length):
        return await self.backdoor.backdoor_read(phys, length)

    async def backdoor_write(self, phys, data):
        await self.backdoor.backdoor_write(phys, data)

    async def validate_backdoor(self, scratch_phys, *, consumers_quiesced,
                                width=16):
        if not consumers_quiesced:
            raise MemoryAccessError("backdoor validation requires quiescent scratch")
        if not self.frontdoor_available:
            raise MemoryAccessError("backdoor proof requires real AXI frontdoor")
        if not isinstance(width, int) or not 1 <= width <= 4096:
            raise ValueError("invalid proof width")
        # Preserve bytes to avoid corrupting another test's data. The caller
        # owns and isolates scratch_phys; validation makes no allocation.
        previous = await self.frontdoor_read(scratch_phys, width)
        first = Pattern("address_xor", seed=0x5a33).chunk(scratch_phys, width)
        second = Pattern("counter8", seed=0x7c12).chunk(scratch_phys, width)
        self.validated_backdoor = False
        try:
            await self.frontdoor_write(scratch_phys, first)
            if await self.backdoor_read(scratch_phys, width) != first:
                raise MemoryMismatch("frontdoor write != backdoor read")
            await self.backdoor_write(scratch_phys, second)
            if await self.frontdoor_read(scratch_phys, width) != second:
                raise MemoryMismatch("backdoor write != frontdoor read")
            self.validated_backdoor = True
        finally:
            # Restore via the real frontdoor, then confirm backdoor view
            # remains coherent. Failed restoration never validates access.
            await self.frontdoor_write(scratch_phys, previous)
            if await self.backdoor_read(scratch_phys, width) != previous:
                self.validated_backdoor = False
                raise MemoryMismatch("backdoor validation scratch restoration failed")


class AxiFrontdoor:
    """Use an existing, explicitly authorized AXI BFM; never create one.

    DO NOT attach this to real-CPU DMA probe response pins. Passive monitors
    remain attached independently and backdoors never count as AXI events.
    """
    validated_backdoor = False
    frontdoor_available = True

    def __init__(self, agent):
        self.agent = agent

    async def frontdoor_read(self, phys, length):
        response = await self.agent.read(phys, length)
        if int(response.resp) != 0:
            raise MemoryAccessError(f"AXI read response {response.resp} at {phys:#x}")
        return bytes(response.data)

    async def frontdoor_write(self, phys, data):
        response = await self.agent.write(phys, data)
        if int(response.resp) != 0:
            raise MemoryAccessError(f"AXI write response {response.resp} at {phys:#x}")

    async def backdoor_read(self, phys, length):
        raise MemoryAccessError("AXI BFM does not implement a backdoor")

    async def backdoor_write(self, phys, data):
        raise MemoryAccessError("AXI BFM does not implement a backdoor")


@dataclass
class MemoryEvent:
    region: str
    token: int
    phase: str
    operation: str
    method: str
    pattern: str
    seed: int
    bytes: int
    wall_ns: int
    simulated_cycles: int | None = None

    def as_dict(self):
        return vars(self).copy()


@dataclass
class _State:
    allocation: VirtualAllocation
    initialized: list[tuple[int, int]] = field(default_factory=list)


class MemoryService:
    """All mode differences are in providers, not test definitions.

    policy='auto': fastest validated method; policy='fast': require
    validated backdoor; policy='strict': frontdoor only; policy='hybrid':
    validated full backdoor + frontdoor edge samples on CHECK. Unsupported
    methods fail closed. A running CPU must use its own CSR/frontdoor or a
    synchronized service mailbox; this class must not preload its cold SRAM.
    """
    def __init__(self, regions: dict[str, VirtualRegion], *,
                 chunk_bytes: int = 4096, cycle_counter=None):
        if not isinstance(chunk_bytes, int) or chunk_bytes < 1:
            raise ValueError("chunk_bytes must be positive")
        self.regions = regions
        self.providers: dict[str, MemoryProvider] = {}
        self.states: dict[tuple[str, int, int], _State] = {}
        self.events: list[MemoryEvent] = []
        self.chunk_bytes = chunk_bytes
        self.cycle_counter = cycle_counter

    def register(self, region: str, provider: MemoryProvider):
        if region not in self.regions:
            raise ValueError(f"unknown region {region}")
        self.providers[region] = provider

    def allocate(self, region: str, size: int, alignment: int, *,
                 owner: str, phase: str) -> VirtualAllocation:
        allocation = self.regions[region].allocate(
            size, alignment, owner=owner, phase=phase)
        self.states[(region, allocation.generation, allocation.token)] = _State(allocation)
        return allocation

    def _state(self, a: VirtualAllocation) -> _State:
        key = (a.region, a.generation, a.token)
        state = self.states.get(key)
        if state is None or state.allocation != a:
            raise MemoryAccessError("stale or unowned allocation handle")
        return state

    def release(self, a: VirtualAllocation, *, consumers_quiesced: bool):
        self._state(a)
        self.regions[a.region].release(a, consumers_quiesced=consumers_quiesced)
        del self.states[(a.region, a.generation, a.token)]

    def observe_completed_write(self, a: VirtualAllocation, *, offset=0,
                                size=None, producer: str,
                                accepted_axi_evidence: bool):
        """Account for a DMA/CPU-produced result WITHOUT initializing it.

        Caller must have independent accepted AXI write / retirement proof,
        not just a descriptor-doorbell or Python plan. The actual CHECK
        still reads physical storage through its selected provider.
        """
        if size is None:
            size = a.size - offset
        if not producer or accepted_axi_evidence is not True:
            raise MemoryAccessError(
                "observed DMA/CPU write requires independent accepted AXI evidence")
        if not isinstance(offset, int) or not isinstance(size, int) or (
                offset < 0 or size < 1 or offset > a.size or size > a.size - offset):
            raise ValueError("observed write outside allocation")
        self._state(a).initialized.append((offset, offset + size))
        self.events.append(MemoryEvent(
            a.region, a.token, a.phase, "observed_write", "passive_axi_evidence",
            "external_producer", 0, size, 0, None))

    def _access(self, a, offset, size, policy, operation):
        self._state(a)
        if not isinstance(offset, int) or offset < 0 or (
                not isinstance(size, int) or size < 0 or offset > a.size
                or size > a.size - offset):
            raise ValueError("memory operation exceeds allocation")
        if size == 0:
            raise ValueError("zero-length memory operation")
        p = self.providers.get(a.region)
        if p is None:
            raise MemoryAccessError(f"{a.region}: no registered memory provider")
        if policy not in ("auto", "fast", "strict", "hybrid"):
            raise ValueError(f"unknown memory policy {policy}")
        backdoor = bool(p.validated_backdoor)
        frontdoor = bool(p.frontdoor_available)
        if policy in ("fast", "hybrid") and not backdoor:
            raise MemoryAccessError("validated backdoor required by policy")
        if policy in ("strict", "hybrid") and not frontdoor:
            raise MemoryAccessError("frontdoor required by policy")
        if policy == "auto":
            if backdoor:
                policy = "fast"
            elif frontdoor:
                policy = "strict"
            else:
                raise MemoryAccessError("no verified access method")
        return p, policy

    @staticmethod
    def _contains(intervals, start, stop):
        covered = start
        for a, b in sorted(intervals):
            if a > covered:
                return False
            covered = max(covered, b)
            if covered >= stop:
                return True
        return False

    async def initialize(self, a: VirtualAllocation, pattern: Pattern, *,
                         offset=0, size=None, policy="auto"):
        if size is None:
            size = a.size - offset
        p, mode = self._access(a, offset, size, policy, "init")
        method = "backdoor" if mode in ("fast", "hybrid") else "frontdoor"
        fn = p.backdoor_write if method == "backdoor" else p.frontdoor_write
        before = self.cycle_counter() if self.cycle_counter else None
        start = time.perf_counter_ns()
        for rel in range(0, size, self.chunk_bytes):
            length = min(self.chunk_bytes, size - rel)
            await fn(a.phys + offset + rel,
                     pattern.chunk(a.phys + offset + rel, length))
        delta = time.perf_counter_ns() - start
        after = self.cycle_counter() if self.cycle_counter else None
        self._state(a).initialized.append((offset, offset + size))
        event = MemoryEvent(a.region, a.token, a.phase, "init", method,
                            pattern.kind, pattern.seed, size, delta,
                            after - before if before is not None else None)
        self.events.append(event)
        return event

    async def check(self, a: VirtualAllocation, pattern: Pattern, *,
                    offset=0, size=None, policy="auto", sample_bytes=16):
        if size is None:
            size = a.size - offset
        p, mode = self._access(a, offset, size, policy, "check")
        if not self._contains(self._state(a).initialized, offset, offset + size):
            raise MemoryAccessError("check of a region without explicit initialization")
        method = "backdoor" if mode in ("fast", "hybrid") else "frontdoor"
        fn = p.backdoor_read if method == "backdoor" else p.frontdoor_read
        before = self.cycle_counter() if self.cycle_counter else None
        start = time.perf_counter_ns()
        async def verify(read, phys, length):
            actual = bytes(await read(phys, length))
            expected = pattern.chunk(phys, length)
            if actual != expected:
                at = next(i for i, (x, y) in enumerate(zip(actual, expected)) if x != y) \
                    if len(actual) == len(expected) else 0
                raise MemoryMismatch(
                    f"{a.region} @{phys+at:#x}: expected {expected[at:at+8].hex()}, "
                    f"got {actual[at:at+8].hex()} [method={method}]")
        for rel in range(0, size, self.chunk_bytes):
            length = min(self.chunk_bytes, size - rel)
            await verify(fn, a.phys + offset + rel, length)
        if mode == "hybrid":
            if not isinstance(sample_bytes, int) or sample_bytes < 1:
                raise ValueError("sample_bytes must be positive")
            n = min(size, sample_bytes)
            await verify(p.frontdoor_read, a.phys + offset, n)
            if size > n:
                await verify(p.frontdoor_read, a.phys + offset + size - n, n)
        elapsed = time.perf_counter_ns() - start
        after = self.cycle_counter() if self.cycle_counter else None
        event = MemoryEvent(a.region, a.token, a.phase, "check",
                            "backdoor+frontdoor-sample" if mode=="hybrid" else method,
                            pattern.kind, pattern.seed, size, elapsed,
                            after - before if before is not None else None)
        self.events.append(event)
        return event
