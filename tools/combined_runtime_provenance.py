"""Compare the canonical combined runtime's actual inputs with the checked source bundle.

The original source-only generator, lock and workspace are not changed. Only
three known firmware-image-bearing files and one source locator can relocate.
No relocated identity is substituted for the actual archived run identity.
"""
from __future__ import annotations

from pathlib import Path
import shlex

try:
    from .generate_combined_variant import (
        PROFILE, VARIANT, SOURCE_ROOT, CombinedGenerationError, digest,
        source_bytes, verify_published_tree,
    )
except ImportError:
    from generate_combined_variant import (
        PROFILE, VARIANT, SOURCE_ROOT, CombinedGenerationError, digest,
        source_bytes, verify_published_tree,
    )

BUNDLE = "gen/projects/xezim_soc_dv/variants/ethernet-ddr-pcie"
BRIDGE = "variant/pcie/pcie_axi_master.v"
LEGACY_BRIDGE = ".tools/pcie0/normalized/pcie_axi_master.v"
PROOF = "combined-runtime-input-equivalence.json"
IMAGES = {
    "variant/soc_top.sv": ("flash.hex", "bootrom.hex"),
    "variant/full_chip_tb.sv": ("compute0.hex", "compute1.hex"),
    "variant/manifest.json": ("flash.hex",),
}


def verify_runtime_inputs(root: Path, out: Path, manifest: dict) -> dict:
    """Prove 312 selected inputs, order, flags and every copied generated byte."""
    if not out.is_relative_to(root / ".tools/runs"):
        raise CombinedGenerationError("combined simulation requires its canonical runtime workspace")
    current = out.relative_to(root).as_posix() + "/"
    if manifest.get("profile") != PROFILE or manifest.get("compiled_top") != "full_chip_tb":
        raise CombinedGenerationError("wrong combined compiler profile")
    if manifest.get("selected_soc_top") != current + "variant/soc_top.sv":
        raise CombinedGenerationError("combined selected top is not run-owned")
    folder = root / BUNDLE
    expected = verify_published_tree(folder, root / "config/soc.yaml")
    if (expected.get("variant") != VARIANT
            or manifest.get("source_count") != 312
            or manifest.get("definition_sha256") != expected.get("selection_sha256")
            or manifest.get("include_headers_sha256") != expected["include_headers_sha256"]
            or manifest.get("defines") != expected["defines"]
            or manifest.get("args") != expected["compiler_args"]
            or manifest.get("network_filelists") != expected["network_filelists"]):
        raise CombinedGenerationError("combined compiler definition, count, headers or flags changed")

    def original(path):
        if path == current + BRIDGE:
            return LEGACY_BRIDGE
        if path.startswith(current):
            return SOURCE_ROOT + path[len(current):]
        if path.startswith(SOURCE_ROOT) or path.startswith(".tools/runs/") or path == LEGACY_BRIDGE:
            raise CombinedGenerationError("combined runtime borrows another run or replay file")
        return path

    def normalize_source(name, sha):
        key = original(name)
        suffix = name.removeprefix(current)
        if suffix in IMAGES and name.startswith(current):
            raw = source_bytes(root, name, sha)
            for image in IMAGES[suffix]:
                live = (current + "variant/" + image).encode("ascii")
                original_ref = (SOURCE_ROOT + "variant/" + image).encode("ascii")
                if raw.count(live) != 1:
                    raise CombinedGenerationError("combined runtime image isn't uniquely run-owned")
                raw = raw.replace(live, original_ref)
            if current.encode("ascii") in raw:
                raise CombinedGenerationError("unreviewed canonical path in combined compiler input")
            return key, digest(raw)
        return key, sha

    def projected(inventory):
        if not isinstance(inventory, dict):
            raise CombinedGenerationError("missing combined compiler inventory")
        pairs = [normalize_source(name, sha) for name, sha in inventory.items()]
        if len(dict(pairs)) != len(pairs):
            raise CombinedGenerationError("duplicate relocated compiler source")
        return dict(pairs)

    if projected(manifest.get("source_sha256")) != expected["selected_source_sha256"]:
        raise CombinedGenerationError("combined runtime compiler source inventory or bytes drifted")
    expected_generated = {
        item["source"]: item["selected_sha256"] for item in expected["files"].values()
        if item["source"].startswith(SOURCE_ROOT)
    }
    expected_generated[LEGACY_BRIDGE] = expected["selected_source_sha256"][LEGACY_BRIDGE]
    if projected(manifest.get("generated_sha256")) != expected_generated:
        raise CombinedGenerationError("combined runtime-generated inputs not equal to reviewed inputs")

    raw = source_bytes(root, current + "sources.f", manifest["filelist_sha256"])
    portable = []
    source_paths = []
    include_paths = []
    for line in raw.decode("utf-8").splitlines():
        tokens = shlex.split(line)
        if len(tokens) != 1:
            raise CombinedGenerationError("invalid combined compiler filelist token")
        line = tokens[0]
        if line.startswith("+define+"):
            portable.append(line)
            continue
        include = line.startswith("+incdir+")
        submitted = Path(line.removeprefix("+incdir+") if include else line)
        if not submitted.is_absolute() or not submitted.is_relative_to(root) or ".." in submitted.parts:
            raise CombinedGenerationError("combined compiler list contains a foreign path")
        name = submitted.relative_to(root).as_posix()
        key = original(name)
        if include:
            if key != name:
                raise CombinedGenerationError("unexpected relocated include directory")
            include_paths.append(name)
            portable.append("+incdir+" + name)
        else:
            source_paths.append(name)
            mapped = expected["portable_source_map"].get(key)
            portable.append(f"{BUNDLE}/{mapped}" if mapped else key)
    projected_list = ("\n".join(portable) + "\n").encode("utf-8")
    if (include_paths != expected["includes"] or len(source_paths) != 312
            or set(source_paths) != set(manifest["source_sha256"])
            or projected_list != (folder / "compiler/sources.f").read_bytes()):
        raise CombinedGenerationError("combined ordered compiler filelist differs from reviewed portable input")
    return {
        "schema_version": 1, "target": PROFILE,
        "scope": "matched_input_bytes_not_simulation_or_bit_connectivity",
        "source_count": 312,
        "actual_filelist_sha256": manifest["filelist_sha256"],
        "actual_compiler_input_sha256": manifest["compiler_input_sha256"],
        "portable_filelist_sha256": expected["portable_filelist_sha256"],
        "portable_compiler_input_sha256": expected["portable_compiler_input_sha256"],
    }
