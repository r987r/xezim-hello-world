"""One eight-mesh FlooNoC wrapper for the upstream cocotbext-axi AXI4 BFMs.

Creates only thin AXI packed-struct <-> flat-port assignments. The instantiated
routers, network interfaces and routing tables are exclusively upstream FlooGen.
"""
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]

AW_FIELDS = {"id":"id", "addr":"addr", "len":"len", "size":"size",
             "burst":"burst", "lock":"lock", "cache":"cache", "prot":"prot",
             "qos":"qos", "region":"region"}
AR_FIELDS = dict(AW_FIELDS)
W_FIELDS = {"data":"data", "strb":"strb", "last":"last"}
B_FIELDS = {"id":"id", "resp":"resp"}
R_FIELDS = {"id":"id", "data":"data", "resp":"resp", "last":"last"}

def emit(soc, noc_root, dest):
    manifest = json.loads((noc_root/"manifest.json").read_text())["networks"]
    confs = {n:yaml.safe_load((noc_root/m["config"]).read_text())
             for n,m in sorted(manifest.items())}
    eps = {n:{e["name"]:e for e in c["endpoints"]} for n,c in confs.items()}
    computes = [x["name"] for x in soc["subsystems"] if x["type"]=="compute"]
    memory = next(x["name"] for x in soc["subsystems"] if x["type"]=="memory")
    links=[]
    for c in computes:
        links.extend([
            ((c+"_local_data","global_out"),("global_data",c)),
            (("global_data",c+"_sram"),(c+"_local_data","global_in")),
            ((c+"_local_config","global_out"),("global_config",c)),
            (("global_config",c+"_regs"),(c+"_local_config","global_in")),
        ])
    for output in soc["networks"]["global_data"]["outputs"]:
        links.append((("global_data",output["name"]),(memory+"_local_data",output["name"])))
    links.append((("global_config",memory+"_regs"),(memory+"_local_config","global_in")))

    def role(k):
        return "in" if eps[k[0]][k[1]].get("mgr_port_protocol") else "out"
    def spec(k):
        n,e=k
        ep=eps[n][e]
        name=(ep.get("mgr_port_protocol") or ep.get("sbr_port_protocol"))[0]
        return next(p for p in confs[n]["protocols"] if p["name"]==name)
    def sig(k,rr):
        return "noc_"+k[0]+"_"+k[1]+"_"+rr
    paired=set()
    for a,b in links:
        if role(a)!="out" or role(b)!="in" or a in paired or b in paired:
            raise ValueError("invalid or duplicated link "+str((a,b)))
        paired.update((a,b))
        for key in ("addr_width","data_width","id_width","user_width"):
            if spec(a)[key]!=spec(b)[key]:
                raise ValueError(f"AXI {key} mismatch {a}={spec(a)[key]} vs {b}={spec(b)[key]}")
    for n in ("global_data","global_config"):
        if any((n,p) not in paired for p in eps[n]):
            raise ValueError("global NoC dangling port "+n)

    onward = dict(links)

    def trace_route(start, address):
        current, path, seen = start, [], set()
        while current not in seen:
            seen.add(current)
            network = current[0]
            path.append(network)
            matches = []
            for endpoint, config in eps[network].items():
                regions = config.get("addr_range", [])
                if isinstance(regions, dict):
                    regions = [regions]
                if any(int(r["base"]) <= address < int(r["base"]) + int(r["size"])
                       for r in regions):
                    matches.append((network, endpoint))
            if len(matches) != 1:
                raise ValueError(f"missing/ambiguous NoC decode {network} @ {address:x}")
            target = matches[0]
            if target not in onward:
                return "s_" + target[0] + "_" + target[1], path
            current = onward[target]
        raise ValueError(f"cyclic NoC route from {start} @ {address:x}")

    sources = ["// Generated by tools/supernoc_gen.py: only AXI port flattening.",
               "// No router, memory model or verification BFM is reinvented.",
               "module soc_noc (",
               "  input logic clk_i,",
               "  input logic rst_ni,"]
    flat=[]
    edges=[]
    duts=[]
    exposed=[]
    for n,neps in sorted(eps.items()):
        pkg=manifest[n]["top_module"]+"_pkg"
        module=manifest[n]["top_module"]
        ports=[".clk_i(clk_i)",".rst_ni(rst_ni)",".test_enable_i(1'b0)"]
        for name in sorted(neps):
            k=(n,name);direction=role(k)
            wires=[sig(k,"req"),sig(k,"rsp")]
            duts.extend([f"  {pkg}::axi_{direction}_req_t {wires[0]};",
                         f"  {pkg}::axi_{direction}_rsp_t {wires[1]};"])
            ports.extend([f".{name}_axi_{direction}_req_{'i' if direction=='in' else 'o'}({wires[0]})",
                          f".{name}_axi_{direction}_rsp_{'o' if direction=='in' else 'i'}({wires[1]})"])
            if k not in paired:
                exposed.append((k,spec(k),direction))
        duts.append(f"  {module} u_{n} (\n    "+",\n    ".join(ports)+"\n  );")
    for a,b in links:
        edges.extend([f"  assign {sig(b,'req')} = {sig(a,'req')};",
                      f"  assign {sig(a,'rsp')} = {sig(b,'rsp')};"])
    for (n,name),protocol,direction in exposed:
        prefix="m_"+n+"_"+name if direction=="in" else "s_"+n+"_"+name
        # AXI master has request-side input/output inversions relative to
        # AXI slave. Cocotbext-axi owns all protocol timing/transactions.
        dims={"id":protocol["id_width"],"addr":protocol["addr_width"],
              "data":protocol["data_width"],"strb":protocol["data_width"]//8,
              "len":8,"size":3,"burst":2,"lock":1,"cache":4,"prot":3,
              "qos":4,"region":4,"resp":2,"last":1,"valid":1,"ready":1}
        channels={"aw":AW_FIELDS,"w":W_FIELDS,"b":B_FIELDS,"ar":AR_FIELDS,"r":R_FIELDS}
        for channel,fields in channels.items():
            # AXI4 ATOP is an optional extension: drive zero for initiators,
            # do not expose it to cocotbext-axi (which does not drive ATOP).
            for short,member in fields.items():
                field=channel+short
                width=6 if short=="atop" else dims[short]
                is_req=channel in ("aw","w","ar")
                # master output AW/W/AR, slave output B/R
                from_flat=(direction=="in") if is_req else (direction=="out")
                port_direction="input" if from_flat else "output"
                decl="" if width==1 else f" [{width-1}:0]"
                flat.append(f"  {port_direction} logic{decl} {prefix}_{field},")
                record="req" if is_req else "rsp"
                path=f"{sig((n,name),record)}.{channel}.{member}"
                if from_flat: edges.append(f"  assign {path} = {prefix}_{field};")
                else: edges.append(f"  assign {prefix}_{field} = {path};")
            for hs in ("valid","ready"):
                field=channel+hs
                # For AW/W/AR valid is request, ready response;
                # for B/R ready is request, valid response.
                is_req=(channel in ("aw","w","ar"))==(hs=="valid")
                from_flat=(direction=="in") if is_req else direction=="out"
                flat.append(f"  {'input' if from_flat else 'output'} logic {prefix}_{field},")
                record="req" if is_req else "rsp"
                path=f"{sig((n,name),record)}.{channel}_{hs}"
                if from_flat:edges.append(f"  assign {path} = {prefix}_{field};")
                else:edges.append(f"  assign {prefix}_{field} = {path};")
        # Upstream transport includes AXI user metadata even when tests
        # do not expose it; zero sidebands are valid for simple AXI4.
        for channel in ("aw","w","ar"):
            if direction=="in":
                edges.append(f"  assign {sig((n,name),'req')}.{channel}.user = '0;")
        if direction=="in":
            edges.append(f"  assign {sig((n,name),'req')}.aw.atop = '0;")
        for channel in ("b","r"):
            if direction=="out":
                edges.append(f"  assign {sig((n,name),'rsp')}.{channel}.user = '0;")
    # A read-only view of each distinct AXI connection. An inter-mesh link
    # is observed once at its source; its two endpoint aliases are cataloged.
    # Upstream cocotbext-axi channel monitors own handshake sampling.
    observations = [(k, None, 'initiator' if d == 'in' else 'target')
                    for k, _, d in exposed] + [(a, b, 'link') for a,b in links]
    taps, catalog = [], []
    for k, peer, kind in observations:
        protocol = spec(k)
        prefix = 'tap_' + k[0] + '__' + k[1]
        dimensions = {'id':protocol['id_width'], 'addr':protocol['addr_width'],
                      'data':protocol['data_width'], 'strb':protocol['data_width']//8,
                      'len':8,'size':3,'burst':2,'lock':1,'cache':4,'prot':3,
                      'qos':4,'region':4,'resp':2,'last':1,'user':protocol['user_width']}
        for channel, fields in {'aw':AW_FIELDS,'w':W_FIELDS,'b':B_FIELDS,
                                'ar':AR_FIELDS,'r':R_FIELDS}.items():
            for member in [*fields.values(), 'user', 'valid', 'ready']:
                request = ((channel in ('aw','w','ar')) == (member != 'ready')) if member in ('valid','ready') else channel in ('aw','w','ar')
                record = sig(k, 'req' if request else 'rsp')
                path = f'{record}.{channel}_{member}' if member in ('valid','ready') else f'{record}.{channel}.{member}'
                width = 1 if member in ('valid','ready') else dimensions[member]
                dim = f' [{width-1}:0]' if width > 1 else ''
                taps += [f'  wire{dim} {prefix}_{channel}{member} = {path};']
        catalog.append({'id':'.'.join(k), 'prefix':prefix, 'role':kind,
                        'endpoints':['.'.join(k)] + (['.'.join(peer)] if peer else []),
                        'network':k[0], 'plane':manifest[k[0]]['plane'],
                        'addr_width':protocol['addr_width'],'data_width':protocol['data_width'],
                        'id_width':protocol['id_width']})
    sources+=flat
    sources[-1]=sources[-1].rstrip(",")
    sources+= [");"]+duts+edges+['`ifdef COCOTB_SIM']+taps+['`endif',"endmodule"]
    dest.parent.mkdir(parents=True,exist_ok=True)
    (dest.parent/"soc_noc.sv").write_text("\n".join(sources)+"\n")
    # One shared fabric assembly; the BFM regression and CPU boot top both
    # instantiate this core instead of maintaining a second topology.
    wrapper = ["// Generated BFM-facing wrapper around the shared NoC core.",
               "module supernoc_tb (", "  input logic clk_i,", "  input logic rst_ni,"] + flat
    wrapper[-1] = wrapper[-1].rstrip(",")
    names = [line.rstrip(",").split()[-1] for line in flat]
    wrapper += [");", "  soc_noc u_noc (", "    " + ",\n    ".join(
        f".{name}({name})" for name in ["clk_i", "rst_ni", *names]), "  );", "endmodule"]
    dest.write_text("\n".join(wrapper)+"\n")
    meta={"top":"supernoc_tb","meshes":len(confs),"links":len(links),
          "connections":[{"from":".".join(a),"to":".".join(b)} for a,b in links],
          "masters":[],"slaves":[]}
    for k,p,d in exposed:
        t={"name":("m_" if d=="in" else "s_")+k[0]+"_"+k[1],
           "network":k[0],"endpoint":k[1],"plane":manifest[k[0]]["plane"],"addr_width":p["addr_width"],
           "data_width":p["data_width"],"id_width":p["id_width"]}
        if d=="in":
            ranges=[]
            for target in eps[k[0]].values():
                regions=target.get("addr_range",[])
                if isinstance(regions,dict):regions=[regions]
                for region in regions:
                    base=int(region["base"])
                    size=int(region["size"])
                    # Include every decoded window regardless of its address.
                    # Boot storage gets routing reads only; real cold boot is
                    # separately tested with ROM and uninitialized SRAM.
                    boot = soc["address_map"]["data"] if t["plane"] == "data" else []
                    readonly = any(x["name"] in ("boot.rom", "boot.flash") and
                                   int(x["base"], 0) == base for x in boot)
                    target, path = trace_route(k, base)
                    if trace_route(k, base + size - 1) != (target, path):
                        raise ValueError(f"destination changes within window {k} @ {base:x}")
                    ranges.append({"base":base,"size":size,
                                   "access":"read" if readonly else "read_write",
                                   "destination":target,"networks":path})
            t["regions"]=sorted(ranges,key=lambda x:x["base"])
            if not ranges:raise ValueError(f"No testable destination for {k}")
            meta["masters"].append(t)
        else:
            regions=eps[k[0]][k[1]].get("addr_range",[])
            if isinstance(regions,dict):regions=[regions]
            t["regions"]=[{"base":int(x["base"]),"size":int(x["size"])} for x in regions]
            meta["slaves"].append(t)
    meta['axi_actors'] = {
        m['network']+'.'+m['endpoint']:{'kind':'verification_bfm','label':'AXI verification BFM (reserved '+m['endpoint']+' boundary)',
                                       'short_label':m['network']+'.'+m['endpoint']+' BFM'}
        for m in meta['masters']}
    meta['axi_actors'].update({
        s['network']+'.'+s['endpoint']:{'kind':'verification_target','label':'AXI verification target BFM'}
        for s in meta['slaves']})
    (dest.parent/"manifest.json").write_text(json.dumps(meta,indent=2,sort_keys=True)+"\n")
    regions = [{'name':r['name'],'plane':plane,'base':r['base'],'size':r['size']}
               for plane in ('data','config') for r in soc['address_map'][plane]]
    (dest.parent/'axi_monitors.json').write_text(json.dumps({
        'schema_version':1, 'scope':'soc_noc', 'monitors':catalog, 'regions':regions,
        'semantics':'One passive observation per distinct AXI connection; IDs are local to each observation.'
    },indent=2,sort_keys=True)+'\n')
    return meta


if __name__=="__main__":
    c=yaml.safe_load((ROOT/"config/soc.yaml").read_text())
    print(emit(c,ROOT/"gen/noc/floonoc",ROOT/"gen/supernoc/supernoc_tb.sv"))
