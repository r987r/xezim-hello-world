"""Generate one real eight-FlooNoC traffic test from upstream FlooGen endpoints.

All buses use the upstream PULP AXI test library (axi_test.sv), not
hand-written BFMs. Generated RTL is source controlled under gen/supernoc/.
"""
import json
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parents[1]
BT = chr(96)

def emit(soc, noc_root, dest):
    manifest = json.loads((noc_root/"manifest.json").read_text())["networks"]
    configs = {n: yaml.safe_load((noc_root / e["config"]).read_text())
               for n,e in manifest.items()}
    endpoints = {n:{p["name"]:p for p in c["endpoints"]} for n,c in configs.items()}
    computes = [s["name"] for s in soc["subsystems"] if s["type"] == "compute"]
    memory = next(s["name"] for s in soc["subsystems"] if s["type"]=="memory")
    links = []
    for c in computes:
        links.extend([
            ((c+"_local_data","global_out"),("global_data",c)),
            (("global_data",c+"_sram"),(c+"_local_data","global_in")),
            ((c+"_local_config","global_out"),("global_config",c)),
            (("global_config",c+"_regs"),(c+"_local_config","global_in")),
        ])
    for out in soc["networks"]["global_data"]["outputs"]:
        links.append((("global_data",out["name"]),(memory+"_local_data",out["name"])))
    links.append((("global_config",memory+"_regs"),(memory+"_local_config","global_in")))

    def direction(k):
        n,p=k
        return "in" if endpoints[n][p].get("mgr_port_protocol") else "out"
    def signal(k,which):
        return "noc_" + k[0] + "_" + k[1] + "_" + which
    def spec(k):
        n,p=k
        ep=endpoints[n][p]
        pname=(ep.get("mgr_port_protocol") or ep.get("sbr_port_protocol"))[0]
        return next(x for x in configs[n]["protocols"] if x["name"]==pname)

    paired=set()
    for a,b in links:
        if direction(a)!="out" or direction(b)!="in":
            raise ValueError(f"invalid NoC interconnect direction {a} -> {b}")
        if a in paired or b in paired:
            raise ValueError(f"duplicate external fabric port {a} -> {b}")
        paired.update((a,b))
        for f in ("addr_width","data_width","id_width","user_width"):
            if spec(a)[f]!=spec(b)[f]:
                raise ValueError(f"incompatible {f}: {a} {spec(a)[f]} -> {b} {spec(b)[f]}")
    for n in ("global_data","global_config"):
        for p in endpoints[n]:
            if (n,p) not in paired:
                raise ValueError(f"global NoC port not connected: {n}.{p}")

    lines=[
        "// GENERATED BY tools/supernoc_gen.py. DO NOT EDIT.",
        "// All eight physical FlooNoC meshes + upstream PULP AXI directed BFMs.",
        BT+'include "axi/assign.svh"',
        "module supernoc_tb;",
        "  timeunit 1ns; timeprecision 1ps;",
        "  logic clk = 0; always #5ns clk = ~clk;",
        "  logic rst_n = 0;",
        "  initial begin repeat (12) @(posedge clk); rst_n = 1; end",
    ]
    for n, eps in sorted(endpoints.items()):
        pkg = manifest[n]["top_module"]+"_pkg"
        for ep in sorted(eps):
            d=direction((n,ep))
            lines.extend([
                f"  {pkg}::axi_{d}_req_t {signal((n,ep),'req')};",
                f"  {pkg}::axi_{d}_rsp_t {signal((n,ep),'rsp')};",
            ])
        ports=[".clk_i(clk)",".rst_ni(rst_n)",".test_enable_i(1'b0)"]
        for ep in sorted(eps):
            d=direction((n,ep))
            ports.extend([
                f".{ep}_axi_{d}_req_{'i' if d=='in' else 'o'}({signal((n,ep),'req')})",
                f".{ep}_axi_{d}_rsp_{'o' if d=='in' else 'i'}({signal((n,ep),'rsp')})",
            ])
        lines.append("  "+manifest[n]["top_module"]+" u_"+n+" (\n    "+",\n    ".join(ports)+"\n  );")

    for a,b in links:
        lines.extend([
            f"  assign {signal(b,'req')} = {signal(a,'req')};",
            f"  assign {signal(a,'rsp')} = {signal(b,'rsp')};",
        ])

    drivers=[];responders=[]
    for n,eps in sorted(endpoints.items()):
        for ep,meta in sorted(eps.items()):
            k=(n,ep)
            if k in paired: continue
            p=spec(k); aw=p["addr_width"];dw=p["data_width"];iw=p["id_width"];uw=p["user_width"]
            key=n+"_"+ep;d=direction(k)
            lines.extend([
                f"  AXI_BUS #(.AXI_ADDR_WIDTH({aw}), .AXI_DATA_WIDTH({dw}), .AXI_ID_WIDTH({iw}), .AXI_USER_WIDTH({uw})) axi_{key}();",
                f"  AXI_BUS_DV #(.AXI_ADDR_WIDTH({aw}), .AXI_DATA_WIDTH({dw}), .AXI_ID_WIDTH({iw}), .AXI_USER_WIDTH({uw})) dv_{key}(clk);",
            ])
            if d=="in":
                lines.extend([
                    "  "+BT+f"AXI_ASSIGN(axi_{key}, dv_{key})",
                    "  "+BT+f"AXI_ASSIGN_TO_REQ({signal(k,'req')}, axi_{key})",
                    "  "+BT+f"AXI_ASSIGN_FROM_RESP(axi_{key}, {signal(k,'rsp')})",
                ])
                regs=[]
                for target in eps.values():
                    ranges=target.get("addr_range",[])
                    if isinstance(ranges,dict):ranges=[ranges]
                    for x in ranges:
                        addr=int(x["base"])
                        if addr>=0x10000000 and addr!=0x20000000 and addr not in regs:
                            regs.append(addr)
                if not regs:raise ValueError("master has no writable address windows: "+key)
                drivers.append((key,aw,dw,iw,uw,regs))
            else:
                lines.extend([
                    "  "+BT+f"AXI_ASSIGN(dv_{key}, axi_{key})",
                    "  "+BT+f"AXI_ASSIGN_FROM_REQ(axi_{key}, {signal(k,'req')})",
                    "  "+BT+f"AXI_ASSIGN_TO_RESP({signal(k,'rsp')}, axi_{key})",
                ])
                responders.append((key,aw,dw,iw,uw))
    lines.append(f"  logic [{len(drivers)-1}:0] done = '0;")

    for key,aw,dw,iw,uw in responders:
        lines.extend([
            f"  typedef axi_test::axi_rand_slave #(.AW({aw}),.DW({dw}),.IW({iw}),.UW({uw}),",
            "     .MAPPED(1'b1),.AX_MIN_WAIT_CYCLES(0),.AX_MAX_WAIT_CYCLES(2),",
            f"     .RESP_MIN_WAIT_CYCLES(0),.RESP_MAX_WAIT_CYCLES(2)) sink_t_{key};",
            f"  sink_t_{key} sink_{key};",
            f"  initial begin : sink_process_{key}",
            f"    sink_{key}=new(dv_{key}); sink_{key}.reset();",
            f"    @(posedge rst_n); sink_{key}.run();",
            "  end",
        ])
    for idx,(key,aw,dw,iw,uw,regions) in enumerate(drivers):
        lines.extend([
            f"  typedef axi_test::axi_driver #(.AW({aw}),.DW({dw}),.IW({iw}),.UW({uw})) drv_t_{key};",
            f"  drv_t_{key} driver_{key};",
            f"  initial begin : stimulus_{key}",
            f"    drv_t_{key}::ax_beat_t ax;",
            f"    drv_t_{key}::w_beat_t wb;",
            f"    drv_t_{key}::b_beat_t br;",
            f"    drv_t_{key}::r_beat_t rr;",
            f"    driver_{key}=new(dv_{key}); driver_{key}.reset_master();",
            "    @(posedge rst_n);",
        ])
        for k,base in enumerate(regions):
            addr=base+0x100+idx*8
            pat=0x5a000000|(idx<<12)|k
            lines.extend([
                "    ax=new; wb=new;",
                f"    ax.ax_id='d1; ax.ax_addr={aw}'h{addr:x};",
                f"    ax.ax_size=$clog2({dw}/8); ax.ax_len=0; ax.ax_burst=axi_pkg::BURST_INCR;",
                f"    wb.w_data={dw}'h{pat:x}; wb.w_strb='1; wb.w_last=1;",
                f"    fork driver_{key}.send_aw(ax); driver_{key}.send_w(wb); join",
                f"    driver_{key}.recv_b(br);",
                f'    if(br.b_resp!=axi_pkg::RESP_OKAY || br.b_id!=1) $fatal(1,"{key} write response {addr:x}");',
                f"    driver_{key}.send_ar(ax);",
                f"    driver_{key}.recv_r(rr);",
                f'    if(rr.r_resp!=axi_pkg::RESP_OKAY || rr.r_id!=1 || !rr.r_last || rr.r_data!={dw}\'h{pat:x}) $fatal(1,"{key} readback {addr:x}");',
            ])
        lines.extend([f'    $display("PASS {key} route readbacks");',
                      f"    done[{idx}]=1'b1;","  end"])
    lines.extend([
        "  initial begin",
        "    wait (&done);",
        f'    $display("PASS supernoc: {len(drivers)} upstream PULP AXI masters, {len(responders)} mapped responders, {len(links)} cross-NoC links, {len(networks)} real meshes");',
        "    $finish;",
        "  end",
        '  initial begin #1000000ns; $fatal(1,"supernoc transaction timeout"); end',
        "endmodule",
    ])
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text("\n".join(lines)+"\n")
    return {"top":"supernoc_tb","networks":len(networks),"links":len(links),
            "masters":len(drivers),"responders":len(responders)}

if __name__=="__main__":
    soc=yaml.safe_load((ROOT/"config/soc.yaml").read_text())
    print(emit(soc,ROOT/"gen/noc/floonoc",ROOT/"gen/supernoc/supernoc_tb.sv"))
