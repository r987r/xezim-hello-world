// Ethernet0 MVP: one pinned physical 1G GMII MAC and one real RX/TX
// descriptor queue each. Each frame uses upstream verilog-axi DMA; completion
// records go to memory via upstream DMA and retire only on accepted CQ AXI B.
// The RX packet and TX packet paths share the SAME MAC, not separate PHYs.
//
// This is an IP core with SIX *separate* AXI masters. The system integration
// owner must aggregate them with pinned upstream AXI mux/ID remapping into
// ethernet0_local_data.packet_dma and connect queue CSRs through Config NoC.
// These physical connections are NOT implied by this module itself.
